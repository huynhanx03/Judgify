var ErrUnsafeFile = errors.New("release manifest authoring: unsafe file")

// AuthoredFileMode is the only mode writeExclusive accepts for a published
// authoring artifact: readable by the operator and the release group, never by
// anyone else, and writable by no one once published. It is a constant rather
// than a literal at each call site because a call site that asked for 0o444
// tripped the world-bit guard and made `release-manifest approve` impossible to
// run at all.
const AuthoredFileMode os.FileMode = 0o440

func ReadDraft(ctx context.Context, path string) (Draft, error) {
	contents, err := readBoundedFile(ctx, path)
	if err != nil {
		return Draft{}, errors.Join(ErrInvalidDraft, err)
	}
	var draft Draft
	if err := decodeStrict(contents, &draft); err != nil {
		return Draft{}, errors.Join(ErrInvalidDraft, err)
	}
	if err := ValidateDraft(draft); err != nil {
		return Draft{}, err
	}
	return draft, nil
}

func ReadApproved(
	ctx context.Context,
	path string,
	releaseID string,
) (problemservice.ApprovedReleaseManifest, error) {
	return releasecatalog.LoadManifest(ctx, path, releaseID)
}

// WriteJSONExclusive publishes one complete immutable document without ever
// replacing an existing path. A same-directory hard link makes publication
// atomic, and the temporary inode is fsynced first.
func WriteJSONExclusive(path string, value any, mode os.FileMode) error {
	var contents bytes.Buffer
	encoder := json.NewEncoder(&contents)
	encoder.SetEscapeHTML(true)
	encoder.SetIndent("", "  ")
	if err := encoder.Encode(value); err != nil {
		return errors.Join(ErrUnsafeFile, err)
	}
	return writeExclusive(path, contents.Bytes(), mode)
}

func WriteSandboxMakefile(path string, draft Draft) error {
	if err := ValidateDraft(draft); err != nil {
		return err
	}
	var output strings.Builder
	output.WriteString("# Generated by `judgify release-manifest sandbox-env`; DO NOT EDIT.\n")
	output.WriteString("# Contains public build identities only; it is not a secret file.\n")
	for _, runtime := range draft.Runtimes {
		prefix, exists := sandboxMakePrefix(runtime.RuntimeKey)
		if !exists {
			return ErrInvalidDraft
		}
		for _, field := range []struct {
			name  string
			value string
		}{
			{name: "PROFILE_VERSION", value: runtime.ProfileVersion},
			{name: "COMPILER_VERSION", value: runtime.CompilerVersion},
			{name: "RUNTIME_BOOTSTRAP_VERSION", value: runtime.RuntimeBootstrapVersion},
			{name: "COMPILE_COMMAND_ID", value: runtime.CompileCommandID},
			{name: "RUN_COMMAND_ID", value: runtime.RunCommandID},
			{name: "MANIFEST_VERSION", value: runtime.ManifestVersion},
			{name: "MANIFEST_CHECKSUM", value: runtime.ManifestChecksum},
		} {
			// A colon is inert inside a Make variable value. It is excluded from
			// this set on purpose: every ManifestChecksum is "sha256:<hex>", so
			// rejecting it made this function fail for every possible draft.
			// The operator "=" stays forbidden, which is what keeps ":=" from
			// reaching a value and being read as a second assignment.
			if strings.ContainsAny(field.value, " \t\r\n#$=\\") {
				return ErrInvalidDraft
			}
			_, _ = fmt.Fprintf(&output, "%s_%s := %s\n", prefix, field.name, field.value)
		}
	}
	return writeExclusive(path, []byte(output.String()), AuthoredFileMode)
}

func readBoundedFile(ctx context.Context, path string) ([]byte, error) {
	if ctx == nil || ctx.Err() != nil || releasecatalog.ValidateFilePath(path) != nil {
		return nil, ErrUnsafeFile
	}
	file, err := os.Open(path)
	if err != nil {
		return nil, errors.Join(ErrUnsafeFile, err)
	}
	defer func() { _ = file.Close() }()
	info, err := file.Stat()
	if err != nil || info.Size() < 1 || info.Size() > releasecatalog.MaximumManifestBytes {
		return nil, errors.Join(ErrUnsafeFile, err)
	}
	contents, err := io.ReadAll(io.LimitReader(file, releasecatalog.MaximumManifestBytes+1))
	if err != nil || len(contents) == 0 || len(contents) > releasecatalog.MaximumManifestBytes {
		return nil, errors.Join(ErrUnsafeFile, err)
	}
	return contents, nil
}

func decodeStrict(contents []byte, value any) error {
	decoder := json.NewDecoder(bytes.NewReader(contents))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(value); err != nil {
		return err
	}
	if err := decoder.Decode(new(struct{})); !errors.Is(err, io.EOF) {
		return ErrUnsafeFile
	}
	return nil
}

func writeExclusive(path string, contents []byte, mode os.FileMode) (resultErr error) {
	if !filepath.IsAbs(path) || filepath.Clean(path) != path ||
		strings.ContainsAny(path, "\x00\r\n") ||
		len(contents) == 0 || len(contents) > releasecatalog.MaximumManifestBytes ||
		mode.Perm()&0o007 != 0 {
		return ErrUnsafeFile
	}
	parent := filepath.Dir(path)
	parentInfo, err := os.Stat(parent)
	if err != nil || !parentInfo.IsDir() {
		return errors.Join(ErrUnsafeFile, err)
	}
	if _, err := os.Lstat(path); err == nil || !errors.Is(err, os.ErrNotExist) {
		return errors.Join(ErrUnsafeFile, err)
	}
	temporary, err := os.CreateTemp(parent, ".judgify-release-*")
	if err != nil {
		return errors.Join(ErrUnsafeFile, err)
	}
	temporaryPath := temporary.Name()
	temporaryOpen := true
	defer func() {
		if temporaryOpen {
			resultErr = errors.Join(resultErr, temporary.Close())
		}
		if removeErr := os.Remove(temporaryPath); removeErr != nil &&
			!errors.Is(removeErr, os.ErrNotExist) {
			resultErr = errors.Join(resultErr, removeErr)
		}
	}()
	if err := temporary.Chmod(mode.Perm()); err != nil {
		return errors.Join(ErrUnsafeFile, err)
	}
	if _, err := temporary.Write(contents); err != nil {
		return errors.Join(ErrUnsafeFile, err)
	}
	if err := temporary.Sync(); err != nil {
		return errors.Join(ErrUnsafeFile, err)
	}
	if err := temporary.Close(); err != nil {
		return errors.Join(ErrUnsafeFile, err)
	}
	temporaryOpen = false
	if err := os.Link(temporaryPath, path); err != nil {
		return errors.Join(ErrUnsafeFile, err)
	}
	directory, err := os.Open(parent)
	if err != nil {
		return errors.Join(ErrUnsafeFile, err)
	}
	if err := directory.Sync(); err != nil {
		_ = directory.Close()
		return errors.Join(ErrUnsafeFile, err)
	}
	if err := directory.Close(); err != nil {
		return errors.Join(ErrUnsafeFile, err)
	}
	return nil
}

func sandboxMakePrefix(runtimeKey string) (string, bool) {
	switch runtimeKey {
	case "cpp17":
		return "CPP17", true
	case "python3":
		return "PYTHON3", true
	case "java17":
		return "JAVA17", true
	case "go":
		return "GO", true
	default:
		return "", false
	}
}
