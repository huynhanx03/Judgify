package inventory

import (
	"fmt"
	"io"
	"strings"
)

const markdownGenerationNotice = "<!-- Code generated by `cd api && go run ./cmd/judgify inventory --format markdown`; DO NOT EDIT. -->\n"

// WriteMarkdown writes the canonical, deterministic Markdown representation of
// a migration inventory report. The output intentionally excludes timestamps
// and machine-specific paths so it can be checked into source control as a
// reproducible receipt.
func WriteMarkdown(writer io.Writer, report Report) error {
	if writer == nil {
		return fmt.Errorf("migration inventory: nil markdown writer")
	}

	write := func(format string, args ...any) error {
		_, err := fmt.Fprintf(writer, format, args...)
		return err
	}

	if err := write("%s\n# Migration Inventory\n\n", markdownGenerationNotice); err != nil {
		return err
	}
	if err := write("- Fingerprint: `%s`\n", report.Fingerprint); err != nil {
		return err
	}
	if err := write("- Migration files: %d\n", len(report.MigrationFiles)); err != nil {
		return err
	}
	if err := write("- Declared tables after replay: %d\n", len(report.DeclaredTables)); err != nil {
		return err
	}
	if err := write("- Ent tables: %d\n\n", len(report.EntTables)); err != nil {
		return err
	}

	if err := write("## Migration Files\n\n| File | Bytes | SHA-256 |\n|---|---:|---|\n"); err != nil {
		return err
	}
	for _, file := range report.MigrationFiles {
		if err := write(
			"| `%s` | %d | `%s` |\n",
			escapeMarkdown(file.Name),
			file.Bytes,
			file.SHA256,
		); err != nil {
			return err
		}
	}

	if err := write("\n## Identifier Mismatches\n\n"); err != nil {
		return err
	}
	if len(report.IdentifierMismatches) == 0 {
		if err := write("None.\n"); err != nil {
			return err
		}
	} else {
		if err := write("| Table | Migration | Ent |\n|---|---|---|\n"); err != nil {
			return err
		}
		for _, mismatch := range report.IdentifierMismatches {
			if err := write(
				"| `%s` | `%s` | `%s` |\n",
				escapeMarkdown(mismatch.Table),
				escapeMarkdown(mismatch.MigrationType),
				escapeMarkdown(mismatch.EntType),
			); err != nil {
				return err
			}
		}
	}

	if err := write("\n## Ent Tables Missing Migration Coverage\n\n"); err != nil {
		return err
	}
	if len(report.MissingMigrations) == 0 {
		if err := write("None.\n"); err != nil {
			return err
		}
	} else {
		for _, table := range report.MissingMigrations {
			if err := write("- `%s`\n", escapeMarkdown(table)); err != nil {
				return err
			}
		}
	}

	if err := write("\n## Destructive SQL\n\n"); err != nil {
		return err
	}
	if len(report.DestructiveSQL) == 0 {
		if err := write("None.\n"); err != nil {
			return err
		}
	} else {
		if err := write("| File | Statement | Kind | Object | Allowed | Reason |\n|---|---:|---|---|---|---|\n"); err != nil {
			return err
		}
		for _, finding := range report.DestructiveSQL {
			if err := write(
				"| `%s` | %d | `%s` | `%s` | %t | %s |\n",
				escapeMarkdown(finding.File),
				finding.Statement,
				finding.Kind,
				escapeMarkdown(finding.Object),
				finding.Allowed,
				escapeMarkdown(finding.Reason),
			); err != nil {
				return err
			}
		}
	}

	if err := write("\n## Parser Diagnostics\n\n"); err != nil {
		return err
	}
	if len(report.Diagnostics) == 0 {
		return write("None.\n")
	}
	if err := write("| File | Statement | Kind | SQL preview |\n|---|---:|---|---|\n"); err != nil {
		return err
	}
	for _, finding := range report.Diagnostics {
		if err := write(
			"| `%s` | %d | `%s` | %s |\n",
			escapeMarkdown(finding.File),
			finding.Statement,
			finding.Kind,
			escapeMarkdown(finding.SQL),
		); err != nil {
			return err
		}
	}
	return nil
}

func escapeMarkdown(value string) string {
	value = strings.ReplaceAll(value, "|", `\|`)
	value = strings.ReplaceAll(value, "\r", " ")
	return strings.ReplaceAll(value, "\n", " ")
}
